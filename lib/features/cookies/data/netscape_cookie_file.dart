/// One cookie in the form the Netscape `cookies.txt` format needs.
class NetscapeCookie {
  const NetscapeCookie({
    required this.domain,
    required this.name,
    required this.value,
    this.path = '/',
    this.secure = true,
    this.httpOnly = false,
    this.expires,
  });

  /// Host the cookie belongs to; a leading dot means "and all subdomains".
  final String domain;
  final String name;
  final String value;
  final String path;
  final bool secure;
  final bool httpOnly;

  /// Expiry time; null for a session cookie.
  final DateTime? expires;

  bool get includeSubdomains => domain.startsWith('.');
}

/// Writes cookies in the Netscape HTTP Cookie File format that yt-dlp
/// (`--cookies`) and gallery-dl (`--cookies`) read:
///
/// ```
/// domain <TAB> includeSubdomains <TAB> path <TAB> secure <TAB> expiry <TAB> name <TAB> value
/// ```
abstract final class NetscapeCookieFile {
  static const header =
      '# Netscape HTTP Cookie File\n'
      '# Generated by SaveKit from the in-app login. Do not edit.\n';

  /// The WebView does not always report an expiry. Session cookies are written
  /// with a far-future one instead of 0, because some cookie loaders drop
  /// entries they consider already expired.
  static const _sessionLifetime = Duration(days: 365);

  static String serialize(Iterable<NetscapeCookie> cookies, {DateTime? now}) {
    final clock = now ?? DateTime.now();
    final buffer = StringBuffer(header)..writeln();
    final seen = <String>{};

    for (final cookie in cookies) {
      if (cookie.name.isEmpty || !_isSafe(cookie.name)) continue;
      if (!_isSafe(cookie.value) || !_isSafe(cookie.domain)) continue;
      if (cookie.domain.isEmpty) continue;
      // Later duplicates of the same cookie would shadow the first one.
      if (!seen.add('${cookie.domain}\t${cookie.path}\t${cookie.name}')) {
        continue;
      }

      final expires = cookie.expires ?? clock.add(_sessionLifetime);
      final expiry = expires.millisecondsSinceEpoch ~/ 1000;
      final path = cookie.path.isEmpty || !_isSafe(cookie.path)
          ? '/'
          : cookie.path;

      buffer
        ..write(cookie.httpOnly ? '#HttpOnly_' : '')
        ..write(cookie.domain)
        ..write('\t')
        ..write(cookie.includeSubdomains ? 'TRUE' : 'FALSE')
        ..write('\t')
        ..write(path)
        ..write('\t')
        ..write(cookie.secure ? 'TRUE' : 'FALSE')
        ..write('\t')
        ..write(expiry)
        ..write('\t')
        ..write(cookie.name)
        ..write('\t')
        ..writeln(cookie.value);
    }
    return buffer.toString();
  }

  /// Tabs and line breaks are the format's separators and cannot be escaped.
  static bool _isSafe(String field) =>
      !field.contains('\t') && !field.contains('\n') && !field.contains('\r');
}
